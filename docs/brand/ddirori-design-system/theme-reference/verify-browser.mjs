import assert from 'node:assert/strict';
import {mkdir, writeFile, readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const {chromium} = await import(process.env.DDIRORI_PLAYWRIGHT_PATH || 'playwright');
const directory = path.dirname(fileURLToPath(import.meta.url));
const output = process.env.DDIRORI_THEME_EVIDENCE || path.join(directory, 'evidence');
const base = process.env.DDIRORI_THEME_URL || 'http://127.0.0.1:8100/catalog/theme-reference.html';
const system = JSON.parse(await readFile(path.join(directory, '../color-system.json'), 'utf8'));
const browser = await chromium.launch({headless:true, ...(process.env.DDIRORI_BROWSER_PATH ? {executablePath:process.env.DDIRORI_BROWSER_PATH} : {})});
const report = {at:new Date().toISOString(),scope:'Isolated common-component compositions; not product/device certification',layouts:[],checks:[],errors:[]};
const check = (name, condition) => {assert(condition, name);report.checks.push(name);};
await mkdir(output, {recursive:true});
try {
  const page = await browser.newPage();
  page.on('pageerror', e => report.errors.push(e.message));
  page.on('response', r => {if(r.status() >= 400) report.errors.push(`${r.status()} ${r.url()}`);});
  for(const width of [320, 840, 1280]) for(const theme of ['light','dark']) for(const accent of system.accents) for(const scale of [1,2]) {
    const name = `${width}-${theme}-${accent.key}-text${scale}`;
    await page.setViewportSize({width,height:1000});
    const url = new URL(base);url.searchParams.set('theme',theme);url.searchParams.set('accent',accent.key);
    await page.goto(url.href);
    await page.evaluate(scale => {document.documentElement.style.fontSize = `${16*scale}px`;},scale);
    await page.evaluate(() => document.fonts.ready);
    check(`${name} page fits`,await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    check(`${name} row slots fit`,await page.locator('.theme-excerpt .dd-item').evaluateAll(rows => rows.every(n => n.scrollWidth <= n.clientWidth && [...n.querySelectorAll('.dd-item-content,.dd-item-trailing')].every(el => el.getBoundingClientRect().right <= n.getBoundingClientRect().right+1))));
    check(`${name} candidate actually applied`,await page.locator('main').evaluate((n,expected) => getComputedStyle(n).getPropertyValue('--dd-action').trim().toLowerCase() === expected.toLowerCase(),theme === 'dark' ? accent.darkAction : accent.action));
    check(`${name} local group inherits surface`,await page.locator('.theme-properties').evaluate(n => {const c=getComputedStyle(n);return c.borderRadius==='12px' && c.padding==='16px' && c.backgroundColor===getComputedStyle(n.querySelector('input')).backgroundColor;}));
    check(`${name} type role`,await page.locator('.dd-item-title').first().evaluate((n,scale) => getComputedStyle(n).fontSize===`${16*scale}px` && getComputedStyle(n).fontWeight==='600',scale));
    report.layouts.push(name);
    if(accent.key==='violet' && scale===1 && width!==840) await page.screenshot({path:path.join(output,`web-${theme}-${width}.png`),fullPage:true});
  }
  await page.goto(base);
  const firstTitle=page.getByRole('button',{name:'프렐류드 · 첫 번째 구간',exact:true});
  const save=page.getByRole('button',{name:'프렐류드 · 첫 번째 구간 저장',exact:true});
  await firstTitle.focus();await page.keyboard.press('Tab');
  check('title and save independent keyboard stops',await save.evaluate(n => n===document.activeElement));
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('.theme-live')?.textContent==='저장했어요.');
  check('save has selection meaning',await save.getAttribute('aria-pressed')==='true');
  check('selected focus remains visible',await save.evaluate(n => n.matches(':focus-visible') && getComputedStyle(n).outlineWidth==='2px'));
  await firstTitle.click();check('open is independent of save',await page.locator('.theme-live').textContent()==='구간 열기 동작을 요청했어요. 실제 문서는 열지 않는 예제입니다.');
  const disabled=page.getByRole('button',{name:'준비 중인 구간 저장'});
  await disabled.evaluate(n => n.focus());check('disabled slot excluded from focus',await disabled.evaluate(n => n!==document.activeElement));
  await page.getByRole('textbox',{name:'이름',exact:true}).fill('');
  await page.getByRole('button',{name:'적용',exact:true}).click();
  const invalid=page.getByRole('textbox',{name:'이름',exact:true});
  check('invalid meaning and explanation',await invalid.getAttribute('aria-invalid')==='true' && await page.getByText('이름을 입력해주세요.',{exact:true}).count()===1);
  await invalid.focus();await page.keyboard.press('Tab');await page.keyboard.press('Shift+Tab');
  check('invalid focus remains visible',await invalid.evaluate(n=>n.matches(':focus-visible') && getComputedStyle(n).outlineWidth==='2px'));
  const selector=page.getByRole('combobox',{name:'테마',exact:true});await selector.focus();await page.keyboard.press('Enter');
  await page.keyboard.press('ArrowDown');await page.keyboard.press('Enter');
  check('shared selector switches real theme',await page.locator('main').getAttribute('data-theme')==='dark');
  const touch=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
  await touch.goto(base);
  const target=await touch.getByRole('button',{name:'적용',exact:true}).boundingBox();
  check('compact keeps touch target',target.width>=48 && target.height>=48);
  await page.emulateMedia({reducedMotion:'reduce'});
  check('recipes introduce no perpetual animation',await page.locator('.theme-properties').evaluate(n=>getComputedStyle(n).animationName==='none'));
  check('no runtime or resource errors',report.errors.length===0);
  report.browser=await browser.version();
  await writeFile(path.join(output,'web-results.json'),JSON.stringify(report,null,2)+'\n');
  console.log(`${report.layouts.length} layouts and ${report.checks.length} checks passed`);
} finally {await browser.close();}
