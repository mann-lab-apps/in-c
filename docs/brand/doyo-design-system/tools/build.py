"""Generate platform tokens and the code-native loading bird. No product writes."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / 'tokens.json').read_text())
GEOMETRY = json.loads((ROOT / 'assets/loader-geometry.json').read_text())


def resolve(value, seen=()):
    if not isinstance(value, str) or not value.startswith('{'):
        return value
    key = value[1:-1]
    if key in seen:
        raise ValueError(f'Alias cycle: {key}')
    target = DATA
    for part in key.split('.'):
        target = target[part]
    return resolve(target, (*seen, key))


def kebab(name):
    return re.sub(r'[A-Z]', lambda m: '-' + m[0].lower(), name)


def path(commands):
    return ' '.join(str(x) for command in commands for x in command)


def write(name, body):
    (ROOT / name).write_text(body.rstrip() + '\n')


themes = {mode: {key: resolve(v) for key, v in values.items()}
          for mode, values in DATA['themes'].items()}
css = ['/* Generated by tools/build.py. Edit tokens.json. Scoped to .doyo. */']
for mode, values in themes.items():
    selector = '.doyo, .doyo[data-theme="light"]' if mode == 'light' else '.doyo[data-theme="dark"]'
    css.append(selector + ' {')
    css.extend(f'  --doyo-{kebab(k)}: {v};' for k, v in values.items())
    css.append('}')
css.append('.doyo {')
for group in ['spacing', 'radius']:
    css.extend(f'  --doyo-{group}-{kebab(k)}: {v}px;' for k, v in DATA[group].items())
for k, v in DATA['score'].items():
    css.append(f'  --doyo-score-{kebab(k)}: {v};')
css.extend([
    f'  --doyo-font-family: {DATA["typography"]["family"]};',
    f'  --doyo-control-size: {DATA["density"]["comfortable"]["control"]}px;',
    f'  --doyo-control-font: {DATA["density"]["comfortable"]["font"] / 16}rem;',
    f'  --doyo-control-gap: {DATA["density"]["comfortable"]["gap"]}px;',
    f'  --doyo-feedback: {DATA["motion"]["feedbackMs"]}ms;',
    f'  --doyo-panel: {DATA["motion"]["panelMs"]}ms;',
    f'  --doyo-loader-cycle: {DATA["motion"]["loaderCycleMs"]}ms;',
    '}',
    '.doyo[data-density="compact"] {',
    f'  --doyo-control-size: {DATA["density"]["compact"]["control"]}px;',
    f'  --doyo-control-font: {DATA["density"]["compact"]["font"] / 16}rem;',
    f'  --doyo-control-gap: {DATA["density"]["compact"]["gap"]}px;',
    '}',
    '@media (pointer: coarse) { .doyo, .doyo[data-density="compact"] { --doyo-control-size: 48px; --doyo-control-font: 1rem; } }',
    '@media (prefers-reduced-motion: reduce) { .doyo { --doyo-feedback: 0ms; --doyo-panel: 0ms; } }',
])
write('generated/tokens.css', '\n'.join(css))
resolved = {**DATA, 'themes': themes}
write('generated/tokens.ts', '// Generated by tools/build.py.\nexport const doyoTokens = ' +
      json.dumps(resolved, ensure_ascii=False, indent=2) + ' as const;')
write('generated/tokens.js', '// Generated by tools/build.py.\nwindow.DoyoTokens = ' +
      json.dumps(resolved, ensure_ascii=False) + ';')
dart = ['// Generated by tools/build.py. Edit tokens.json.', 'abstract final class DoyoTokens {']
for mode, values in {**themes, 'score': DATA['score'], 'brand': DATA['brand']}.items():
    dart.append(f'  static const {mode} = <String, int>{{')
    dart.extend(f"    '{k}': 0xFF{v[1:]}," for k, v in values.items())
    dart.append('  };')
dart.append(f'  static const loaderCycleMs = {DATA["motion"]["loaderCycleMs"]};')
for name in ['loaderBodyDrop', 'loaderReach', 'loaderFrontSwing', 'loaderSupportScale', 'loaderBodyTilt']:
    dart.append(f'  static const {name} = {float(DATA["motion"][name])};')
for density in ['comfortable', 'compact']:
    dart.append(f'  static const {density}Control = {DATA["density"][density]["control"]}.0;')
dart.append('}')
write('generated/doyo_tokens.dart', '\n'.join(dart))
dart_geometry = ['// Generated from assets/loader-geometry.json.', 'abstract final class DoyoLoaderGeometry {']
dart_geometry.append('  static const eye = <double>[' + ', '.join(str(float(n)) for n in GEOMETRY['eye']) + '];')
for key, origin in GEOMETRY['origins'].items():
    dart_geometry.append(f'  static const {key}Origin = <double>[' + ', '.join(str(float(n)) for n in origin) + '];')
for key in ['body', 'rearLeg', 'frontLeg']:
    dart_geometry.append(f'  static const {key} = <List<Object>>[')
    dart_geometry.extend('    ' + json.dumps(c) + ',' for c in GEOMETRY[key])
    dart_geometry.append('  ];')
dart_geometry.append('}')
write('generated/doyo_loader_geometry.dart', '\n'.join(dart_geometry))
eye_x, eye_y, eye_r = GEOMETRY['eye']
eye = f'M {eye_x-eye_r} {eye_y} a {eye_r} {eye_r} 0 1 0 {eye_r*2} 0 a {eye_r} {eye_r} 0 1 0 {-eye_r*2} 0 Z'
body = path(GEOMETRY['body']) + ' ' + eye
groups = (f'<path data-part="rear-leg" d="{path(GEOMETRY["rearLeg"])}"/>'
          f'<path data-part="front-leg" d="{path(GEOMETRY["frontLeg"])}"/>'
          f'<path data-part="body" fill-rule="evenodd" d="{body}"/>')
def motion_rules(prefix=''):
    m = DATA['motion']
    duration = f'var(--doyo-loader-cycle,{m["loaderCycleMs"]}ms)'
    rules = [f'{prefix}[data-part]{{fill:currentColor;transform-box:view-box}}']
    for part, key in [('body', 'body'), ('rear-leg', 'rearLeg'), ('front-leg', 'frontLeg')]:
        x, y = GEOMETRY['origins'][key]
        rules.append(f'{prefix}[data-part="{part}"]{{transform-origin:{x}px {y}px;animation:doyo-{part} {duration} ease-in-out infinite}}')
    translation = f'translate({-m["loaderReach"]}px,{m["loaderBodyDrop"]}px)'
    rules.extend([
        '@keyframes doyo-body{0%,100%{transform:translate(0,0) rotate(0deg)}50%{transform:' + translation + f' rotate({m["loaderBodyTilt"]}deg)' + '}}',
        '@keyframes doyo-rear-leg{0%,100%{transform:scaleY(1)}50%{transform:scaleY(' + str(m['loaderSupportScale']) + ')}}',
        '@keyframes doyo-front-leg{0%,100%{transform:translate(0,0) rotate(0deg)}50%{transform:' + translation + f' rotate({m["loaderFrontSwing"]}deg)' + '}}',
        f'@media(prefers-reduced-motion:reduce){{{prefix}[data-part]{{animation:none!important}}}}',
    ])
    return '\n'.join(rules)


write('generated/loader-motion.css', motion_rules('.doyo-bird '))
style = ('svg{color:#3E332F}\n' + motion_rules() +
         '\n@media(prefers-color-scheme:dark){svg{color:#F1ECE5}}')
write('assets/doyo-loader.svg', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 164" role="img" aria-label="불러오는 중인 도요새"><style>' + style + '</style>' + groups + '</svg>')
write('assets/doyo-loader-still.svg', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 164" role="img" aria-label="도요새" fill="#3E332F">' + groups.replace('data-part=', 'data-shape=') + '</svg>')
write('generated/loader-markup.html', '<svg class="doyo-bird" viewBox="0 0 256 164" aria-hidden="true">' + groups + '</svg>')
write('generated/loader.js', '// Generated by tools/build.py.\nwindow.DoyoLoaderMarkup = ' +
      json.dumps('<svg class="doyo-bird" viewBox="0 0 256 164" aria-hidden="true">' + groups + '</svg>') + ';')
print('Generated CSS, TypeScript, Dart, loader geometry and SVG/HTML from canonical JSON.')
