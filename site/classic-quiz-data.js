const createWork = ({
  id,
  composerKo,
  composerEn,
  titleKo,
  titleEn,
  nicknameKo,
  era,
  difficulty,
  sourceUrl,
  notesKo,
  confusionNoteKo,
  searchAliasesKo,
  familiarReasonKo,
  modeTags,
  motif,
  bass,
  tempo,
  synth
}) => {
  const audioRights = clearedAudioByWorkId[id]
  const defaultClipDuration = difficulty === '입문' ? 7 : 9

  return {
    id,
    composerKo,
    composerEn,
    titleKo,
    titleEn,
    nicknameKo,
    era,
    difficulty,
    audioUrl: audioRights?.audioUrl ?? '',
    localAudioPath: audioRights?.localAudioPath ?? '',
    audioFormat: audioRights?.audioFormat ?? 'web-audio',
    audioSizeBytes: audioRights?.audioSizeBytes ?? 0,
    audioDurationSeconds: audioRights?.audioDurationSeconds ?? defaultClipDuration,
    audioChecksum: audioRights?.audioChecksum ?? '',
    clipStart: audioRights?.clipStart ?? 0,
    clipDuration: audioRights?.clipDuration ?? defaultClipDuration,
    sourceName: audioRights?.sourceName ?? 'in C Web Audio demo',
    sourceUrl: audioRights?.sourceUrl ?? sourceUrl,
    license: audioRights?.license ?? 'demo-only',
    licenseUrl: audioRights?.licenseUrl ?? '',
    performer: audioRights?.performer ?? 'in C demo synth',
    performerUrl: audioRights?.performerUrl ?? '',
    rightsVerifiedAt: audioRights?.rightsVerifiedAt ?? '',
    notesKo,
    confusionNoteKo:
      confusionNoteKo ??
      `${composerKo}의 ${era} 시대 색깔과 ${nicknameKo || titleKo}의 첫 인상을 함께 묶어두면 다음번에 빨라집니다.`,
    searchAliasesKo,
    familiarReasonKo,
    modeTags,
    verifiedAudioStatus: audioRights?.verifiedAudioStatus ?? AUDIO_STATUS.DEMO,
    rightsNotes: audioRights?.rightsNotes ?? rightsNote,
    attributionRequired: audioRights?.attributionRequired ?? false,
    commercialUseAllowed: audioRights?.commercialUseAllowed ?? false,
    derivativesAllowed: audioRights?.derivativesAllowed ?? false,
    shareAlikeRequired: audioRights?.shareAlikeRequired ?? false,
    motif,
    bass,
    tempo,
    synth
  }
}

