import { createReorderedWholeChordTieScore, createWholeChordTieScore } from './chord-tie-fixture'
import type { Note } from '../score-core'

export type RepeatTieCase = 'internal' | 'exit' | 'entry' | 'middle' | 'volta'

export function createRepeatTieFixture(kind: RepeatTieCase, chord: boolean) {
  const score = chord ? createReorderedWholeChordTieScore(false, true) : createWholeChordTieScore(false, false)
  const measures = score.parts[0].staves[0].measures
  const note = (index: number) => measures[index].voices[0].events[0] as Note
  if (kind === 'middle' || kind === 'volta') {
    const third = structuredClone(measures[1]); third.id = 'chord-tie-measure-3'; third.number = 3
    third.voices[0].events[0].id = 'chord-tie-3'; measures.push(third)
    note(2).ties = kind === 'middle' ? { stop: true } : undefined
  }
  if (kind === 'internal' || kind === 'volta') {
    measures[0].repeat = { start: true }; measures[1].repeat = { end: true, times: 2 }
  } else {
    measures[kind === 'exit' ? 0 : 1].repeat = { start: true, end: true, times: 2 }
  }
  if (kind === 'middle') note(1).ties = { stop: true, start: true }
  if (kind === 'volta') {
    measures[1].volta = { number: 1, start: true, end: true }
    measures[2].volta = { number: 2, start: true, end: true }
  }
  // Explicit performance oracle, not generated by the product repeat planner.
  const order = kind === 'internal' || kind === 'volta' ? [0, 1, 0, kind === 'volta' ? 2 : 1]
    : kind === 'exit' ? [0, 0, 1] : kind === 'entry' ? [0, 1, 1] : [0, 1, 1, 2]
  const links = kind === 'internal' || kind === 'middle' ? [0, 2] : kind === 'exit' ? [1] : [0]
  const expanded = structuredClone(score)
  expanded.parts[0].staves[0].measures = order.map((sourceIndex, index) => {
    const measure = structuredClone(measures[sourceIndex]); measure.id = `expanded-${index}`; measure.number = index + 1
    delete measure.repeat; delete measure.volta
    const event = measure.voices[0].events[0] as Note; event.id = `expanded-note-${index}`
    event.ties = links.includes(index) || links.includes(index - 1)
      ? { start: links.includes(index) || undefined, stop: links.includes(index - 1) || undefined } : undefined
    return measure
  })
  const expected = kind === 'internal' || kind === 'middle' ? [[0, 8], [8, 8]]
    : kind === 'exit' ? [[0, 4], [4, 8]] : kind === 'entry' ? [[0, 8], [8, 4]] : [[0, 8], [8, 4], [12, 4]]
  return { score, expanded, expected }
}
